<h4>IP Protection </h4>
<p>If you attach a backtest or live trading deployment when you <a href="/docs/v2/cloud-platform/organizations/support#06-Open-New-Tickets">open a support ticket</a>, the intellectual property of your project is protected. We have a restricted subset of the Support Team who can access private support tickets. Using paid support plans ensures only a limited subset of the QuantConnect team can access the algorithms you attach to support tickets. These team members are carefully selected, have been at QuantConnect for at least 2 years, and have passed a background check. In contrast, if you share a backtest or live trading deployment to the forum for assistance, your project becomes part of the public domain.</p>

