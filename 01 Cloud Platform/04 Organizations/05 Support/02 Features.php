<h4>Bug Reports</h4>
<p>The Lean trading engine is under constant development, so you may occasionally experience bugs when using it. If you think you have found a bug, share a simple backtest with us that reproduces the issue. You can contact us either through <a href="/contact">email</a>, <a href="/docs/v2/cloud-platform/community/discord">Discord</a>, or the <a href="/docs/v2/cloud-platform/community/forum">forum</a>. We will review your submission. If we confirm you've found a bug, we will create a GitHub Issue to have it resolved. Subscribe to the GitHub Issue to track our progress in fixing the bug.</p>
<p>If you find an issue in historical data, we recommend you <a href="/docs/v2/cloud-platform/datasets/data-issues#04-Report-New-Issues">report it on the Data Issues page</a> of the dataset portal.</p>

