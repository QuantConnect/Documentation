<p>The following table describes the server statistics:</p>

<table class='qc-table table'>
  <thead>
    <tr>
      <th style='width: 25%'>Statistic</th>
      <th style='width: 75%'>Description</th>
    </tr>
  </thead>
  <tbody>
  <tr>
    <td>CPU Usage</td>
    <td>Percentage of the node CPU in use.</td>
  </tr>
  <tr>
    <td>Used RAM (MB)</td>
    <td>RAM the algorithm uses, in megabytes.</td>
  </tr>
  <tr>
    <td>Total RAM (MB)</td>
    <td>RAM the node provides, in megabytes.</td>
  </tr>
  <tr>
    <td>Hostname</td>
    <td>Name of the machine that runs the algorithm, which starts with the type of deployment.</td>
  </tr>
  <tr>
    <td>LEAN Version</td>
    <td>Version of LEAN that runs the algorithm.</td>
  </tr>
  <tr>
    <td>Up Time</td>
    <td>Time the node has been running, in days, hours, minutes, and seconds.</td>
  </tr>
</tbody>
</table>

<p>The available statistics depend on the version of LEAN that produces the results. Results from before LEAN reported the server statistics don't have them.</p>
